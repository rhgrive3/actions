// Native NetSession / Transport / NetMatch / Match over a deterministic fake
// WebSocket platform. The relay acknowledgements are supplied by the test;
// this is not an actual relay or browser/device test.
import test from 'node:test';
import assert from 'node:assert/strict';
import {sourceLoadedActorFixture} from '../../splatoon3/tests/source-loaded-actor-fixture.mjs';
const extraExports=`
 export {NetSession} from './src/net/session.js';
 export {PROTO,COMPAT} from './src/net/transport.js';
 export const installTestSocket=(Socket,interval,cancel)=>{globalThis.WebSocket=Socket;globalThis.location={search:'',hostname:'localhost'};globalThis.setInterval=interval;globalThis.clearInterval=cancel;};
`;
const until=async(fn,label)=>{for(let n=0;n<100;n++){if(fn())return;await new Promise(r=>setTimeout(r,10));}throw Error('Timed out: '+label);};

test('real session START, native initial spawn, rematch and socket retirement use fresh match and transport',async()=>{
 const f=await sourceLoadedActorFixture({extraExports});await f.make();f.reset();
 const sockets=[];class Socket{constructor(url){this.url=url;this.readyState=1;this.bufferedAmount=0;this.sent=[];sockets.push(this);}send(s){this.sent.push(s);}close(){this.readyState=3;this.onclose?.({reason:'bye'});}}
 f.installTestSocket(Socket,setInterval,clearInterval);
 const {G}=f;let match=null,aborted=0;
 G.game={settings:{},profile:{weapon:'charger',name:'Owner'},menus:{current:null},netMatchAborted(){aborted++;},
  async startNetMatch(cfg,net){match=new f.Match({...cfg,myId:net.myId,host:net.isHost,CharacterClass:f.Character});G.match=match;G.mode='match';match.setup();await Promise.all(match.actors.map(a=>a.character._sourceMotionLoader));net.bind(match);this.match=match;},
  netMatchGo(){match.start();}};
 const session=new f.NetSession();G.net=session;
 async function connect(){
  const promise=session.join('ABCDE','Owner');const ws=sockets.at(-1);assert(ws);
  ws.onmessage({data:JSON.stringify({t:'welcome',proto:f.PROTO,compat:f.COMPAT,id:'owner',host:'owner',members:[{id:'owner',name:'Owner'}],relayClock:1})});await promise;
  ws.onmessage({data:JSON.stringify({t:'join',m:{id:'peer',name:'Peer'}})});
  assert.equal(session.state,'lobby');assert.equal(session.lobby.players.length,2);
  return ws;
 }
 async function start(ws){
  session.setSettings({map:'reef',bots:false});session.confirmTeams();session.setMe({ready:true});
  ws.onmessage({data:'m|peer|'+JSON.stringify({k:'me',ready:true,weapon:'shooter'})});
  assert.equal(session.canStart(),true);assert.equal(session.start(),true);
  const sent=ws.sent.filter(s=>s.startsWith('b|')).map(s=>JSON.parse(s.slice(2))),cfg=sent.findLast(x=>x.k==='start');assert.ok(cfg?.id);
  // The nonce/id above is generated by the real session. The fake relay echoes it.
  ws.onmessage({data:JSON.stringify({t:'start_result',id:cfg.id,ok:true})});
  await until(()=>session.state==='starting'&&session._setupReady,'native match setup');
  ws.onmessage({data:'m|peer|'+JSON.stringify({k:'ready',id:cfg.id})});
  await until(()=>session.state==='match','native GO');
  assert.equal(session.match.match,match);assert.equal(match.state,'intro');assert.equal(match.local.s3.squidSpawn.phase,'aim');
  return {cfg,net:session.match,actor:match.local,match};
 }
 try{
  const ws=await connect(),one=await start(ws);const firstLife=one.actor.netLife;
  assert.equal(firstLife,1);for(let i=0;i<3;i++){G.time+=1/60;one.match.update(1/60);}
  assert.equal(one.actor.s3.squidSpawn.phase,'aim');
  session.endMatch();one.match.dispose();
  const two=await start(ws);assert.notEqual(two.cfg.id,one.cfg.id,'native new match epoch');assert.notEqual(two.actor,one.actor);assert.equal(two.actor.netLife,1);assert.equal(two.actor.s3.squidSpawn.phase,'aim');
  const staleHandler=ws.onmessage;ws.close();assert.equal(two.net._disposed,true);assert.equal(session.match,null);assert.equal(session.state,'offline');
  two.match.dispose();const replacement=await connect();assert.notEqual(replacement,ws);assert.equal(session.state,'lobby');
  const active=session.tr;staleHandler?.({data:JSON.stringify({t:'start_result',id:one.cfg.id,ok:true})});
  assert.equal(session.tr,active);assert.equal(session.state,'lobby');assert.equal(session.match,null);assert.equal(aborted,1);
  const three=await start(replacement);assert.notEqual(three.cfg.id,two.cfg.id);assert.notEqual(three.net,two.net);
  assert.equal(three.actor.owner,'owner');assert.equal(three.actor.netLife,1);assert.equal(three.actor.s3.squidSpawn.phase,'aim');
  staleHandler?.({data:'m|peer|'+JSON.stringify({k:'go',id:one.cfg.id})});
  assert.equal(session.match,three.net);assert.equal(three.match.state,'intro');
 }finally{session.leave(true);match?.dispose();f.reset();}
});
