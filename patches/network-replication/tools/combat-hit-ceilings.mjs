// Build/test-only (Node): derive the per-equipped-slot hit ceilings that
// combat-provenance.mjs applies to remote PvP `hit` and Boss `bhit` claims.
// Regenerate the shipped table with:
//   node patches/network-replication/tools/combat-hit-ceilings.mjs --write
import fs from 'node:fs';
import { pathToFileURL } from 'node:url';
import { productionHitDefinitions, CATALOGUE_SUB_HIT_MAX } from '../../reliability/net-hit-payload-adapter.mjs';
import { MAIN_WEAPON_CATALOG } from '../../splatoon3/runtime/main-weapon-catalog-data.mjs';
import { SUB_NAMES, SPECIAL_NAMES } from '../../splatoon3/runtime/catalogue.mjs';
import { ALL_SUB_SPECS } from '../../splatoon3/runtime/all-subs.mjs';
import { damageLeafMax } from '../damage-leaves.mjs';

const DATA = new URL('../combat-hit-ceilings-data.mjs', import.meta.url);

// A guest multiplies its Boss body damage by the native BOSS table before it
// sends `bhit` (boss.js hit(): weak point, stunned). Read those exact values.
export function bossMultipliers(source = fs.readFileSync(new URL('../../../inkwave-public/src/boss/boss.js', import.meta.url), 'utf8')) {
  const rows = [...source.matchAll(/^\s*weak: ([0-9.]+), stunned: ([0-9.]+),/gm)];
  if (rows.length !== 1) throw Error('combat hit ceiling Boss multiplier identity mismatch');
  const weak = Number(rows[0][1]), stunned = Number(rows[0][2]);
  if (!(weak >= 1 && stunned >= 1)) throw Error('combat hit ceiling Boss multiplier shape mismatch');
  return { weak, stunned };
}
const round = n => Math.round(n * 1000) / 1000;
export function computeCombatHitCeilings() {
  const { weapons, subs, specials, specialDescriptors } = productionHitDefinitions();
  const main = {}, sub = {}, special = {};
  for (const [id, def] of Object.entries(weapons)) main[id] = damageLeafMax(def);
  for (const r of MAIN_WEAPON_CATALOG.records) main[r.id] = Math.max(main[r.id] || 0, damageLeafMax(r.parameters, 10));
  for (const id of new Set([...Object.keys(subs), ...Object.keys(SUB_NAMES), ...Object.keys(ALL_SUB_SPECS)]))
    sub[id] = Math.max(damageLeafMax(subs[id]), damageLeafMax(ALL_SUB_SPECS[id]), CATALOGUE_SUB_HIT_MAX[id] || 0);
  sub['torpedo-splash'] = CATALOGUE_SUB_HIT_MAX['torpedo-splash'];
  for (const id of new Set([...Object.keys(specials), ...Object.keys(SPECIAL_NAMES)])) {
    const max = Math.max(damageLeafMax(specials[id]), ...(specialDescriptors[id] || []).map(d => damageLeafMax(d)));
    // No authored damage field: keep that Special's existing provenance policy.
    special[id] = max > 0 ? max : null;
  }
  const sorted = o => Object.fromEntries(Object.keys(o).sort().map(k => [k, o[k] === null ? null : round(o[k])]));
  return { main: sorted(main), sub: sorted(sub), special: sorted(special), boss: bossMultipliers() };
}
export function renderCombatHitCeilings(table = computeCombatHitCeilings()) {
  return '// Generated by patches/network-replication/tools/combat-hit-ceilings.mjs --write. Do not edit.\n' +
    '// Per-equipped-slot maximum player damage of one remote hit claim (#1665/#1666).\n' +
    'export const COMBAT_HIT_CEILINGS = Object.freeze(' + JSON.stringify(table, null, 1) + ');\n';
}
if (import.meta.url === pathToFileURL(process.argv[1] || '').href) {
  const text = renderCombatHitCeilings();
  if (process.argv.includes('--write')) fs.writeFileSync(DATA, text);
  else if (fs.readFileSync(DATA, 'utf8') !== text) { console.error('combat-hit-ceilings-data.mjs is stale; rerun with --write'); process.exit(1); }
}
