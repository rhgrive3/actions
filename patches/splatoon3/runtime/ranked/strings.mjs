export function rankedText(lang, text, vars) {
  const translated = lang === 'ja' ? RANKED_JA[text] ?? text : text;
  return vars ? translated.replace(/\{(\w+)\}/g, (match, key) => key in vars ? String(vars[key]) : match) : translated;
}
