import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';
// Deliberately narrow bundler for our six closed, named-export DSP modules.
// Produces a classic Worker, including for browsers that reject module workers.
const root=fileURLToPath(new URL('../../',import.meta.url)),entry='patches/splatoon3/runtime/audio/render-worker.mjs',out=entry.replace('.mjs','.js');
const seen=new Map(),sources=[],order=[];
function visit(file){if(seen.has(file))return seen.get(file);const id=seen.size;seen.set(file,id);let text=fs.readFileSync(path.join(root,file),'utf8');sources.push([file,createHash('sha256').update(text).digest('hex')]);const exports=[];
 text=text.replace(/^import\s*\{([^}]+)\}\s*from\s*['"]([^'"]+)['"];?\s*$/gm,(_all,names,spec)=>{
  if(!spec.startsWith('.'))throw new Error('Only local named imports allowed');const next=path.posix.normalize(path.posix.join(path.posix.dirname(file),spec));if(next.startsWith('../'))throw new Error('Out of root import');const dep=visit(next);
  return `const {${names.replace(/\bas\b/g,':')}}=modules[${dep}];`;
 });
 text=text.replace(/^export\s+(const|let|function|class)\s+(\w+)/gm,(_all,kind,name)=>{exports.push(name);return `${kind} ${name}`;});
 if(/^\s*(import|export)\b/m.test(text))throw new Error('Unsupported module syntax in '+file);
 order.push(`modules[${id}]=(()=>{\n${text}\nreturn {${exports.join(',')}};\n})();`);return id;
}
visit(entry);
const code=`// GENERATED by tools/audio/build-worker.mjs. Do not edit this bundle.\n// Source SHA256: ${JSON.stringify(sources)}\n(()=>{'use strict';const modules=[];\n${order.join('\n')}\n})();\n`;
if(process.argv.includes('--check')){if(fs.readFileSync(path.join(root,out),'utf8')!==code)throw new Error('DSP worker bundle is stale');console.log('worker bundle is current');}
else{fs.writeFileSync(path.join(root,out),code);console.log(out,Buffer.byteLength(code),'bytes');}
