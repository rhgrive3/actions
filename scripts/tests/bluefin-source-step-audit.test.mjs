import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import {nativeFixture,readStage} from '../../patches/native-stages/tests/fixture.mjs';
import {createBluefinSourceStepAudit} from '../lib/bluefin-source-step-audit.mjs';

const root=process.env.INKWAVE_NATIVE_STAGE_ASSETS;
const ready=root&&fs.existsSync(path.join(root,'bluefin','manifest.json'));
test('source-step audit authenticates actual discrete body expansion and rejects unsupported exceptions',{skip:!ready},async()=>{
 const f=await nativeFixture({includeCharacter:true}),{G,THREE,PLAYER}=f;
 const data=readStage(root,'bluefin');G.level=new f.NativeLevel(data);G.physics=new f.NativePhysics(G.level);
 class Cpu extends f.PaintSystem{_initGPU(){this.quads=0;this.dryMesh={visible:false};this._dryU={uDry:{value:0}};} _pushQuad(){} _drawQuads(){}}
 G.paint=new Cpu(null,G.level,{atlasSize:2048,maxDensity:4,cell:.25});G.match.mode='turf';G.match.opts={};G.camera=new THREE.PerspectiveCamera();
 const a=new f.Actor({team:1,name:'profile control',weapon:'shooter',CharacterClass:f.Character,style:{hair:0,skin:2,outfit:0,eyes:0}});G.actors=[a];
 a.spawnAt(new THREE.Vector3(-27,3,-17.5),-Math.PI/2);a.invuln=0;a.intent.move.set(-1,0,0);a.intent.squid=true;
 const hash=()=>crypto.createHash('sha256').update(Buffer.from(data.triangles.buffer)).update(Buffer.from(data.flags.buffer)).update(Buffer.from(data.mask.buffer)).digest('hex'),before=hash();
 const original={contacts:G.physics._nativeContacts,triangle:G.level.triangleWorld.triangle,distance:G.level.triangleWorld._capsuleDistance};
 const audit=createBluefinSourceStepAudit(G,a,PLAYER,f.nativeDropClearance(G.level));
 G.time+=1/60;const checked=audit.run(1/60,()=>a.update(1/60));
 assert.equal(checked.result.ok,true);assert.equal(checked.result.kind,'discrete-source-expansion');assert.equal(checked.result.contacts,1);
 assert.equal(checked.record.oldProfile.form,'kid');assert.equal(checked.record.currentProfile.form,'squid');
 assert.equal(checked.record.solves[0].contacts[0].triangle,91050);
 assert.ok(checked.record.committed[0]>checked.record.previous[0],'actual source wall pushes the expanded body outwards');
 for(const key of ['contacts','triangle','distance'])assert.equal(key==='contacts'?G.physics._nativeContacts:key==='triangle'?G.level.triangleWorld.triangle:G.level.triangleWorld._capsuleDistance,original[key]);
 const negative=(name,mutate)=>{const record=structuredClone(checked.record);mutate(record);assert.equal(audit.verify(record).ok,false,name);};
 negative('no recorded solver',r=>r.solves=[]);
 negative('no authenticated contact',r=>r.solves[0].contacts=[]);
 negative('ceiling correction is not a wall expansion',r=>r.solves[0].ceiling=true);
 negative('source contact distance must match',r=>r.solves[0].contacts[0].distance+=.02);
 negative('source normal must match',r=>r.solves[0].contacts[0].normal=[-1,0,0]);
 negative('unexplained committed teleport',r=>r.committed=[-20,3,-17.5]);
 negative('expanded committed body still penetrates',r=>r.committed=[-27.1,3,-17.5]);
 negative('expanded shape cannot be retroactively called the previous actual body',r=>r.oldProfile={...r.currentProfile});
 negative('airborne expansion has no immediate source support',r=>{r.previous[1]+=.2;});
 negative('wrong solve profile',r=>r.solves[0].radius+=.01);
 negative('fabricated smaller actual body',r=>r.currentProfile.radius=.1);
 G.time+=1/60;const same=audit.run(1/60,()=>a.update(1/60));assert.equal(same.result.ok,true);assert.equal(same.result.kind,'continuous');
 const through=structuredClone(same.record);through.committed=[-28.3,3,-17.5];assert.equal(audit.verify(through).ok,false,'same-form source-wall crossing never inherits the expansion exception');
 const pop={dt:1/60,previous:[26.8249,7.719342121169873,18.50035776361281],committed:[26.8549,7.962397676725429,18.50035776361281],oldProfile:{...checked.record.currentProfile},currentProfile:{...checked.record.oldProfile},solves:[]};
 const clearance=f.nativeDropClearance(G.level),vector=p=>new THREE.Vector3(...p),sweep=p=>clearance.clear(vector(pop.previous),vector(pop.committed),p.radius,p.lift,p.height,p.skipGrates);
 assert.equal(sweep(pop.oldProfile),false,'retired wide squid profile would incorrectly clip the wall during the recorded kid pop');
 assert.equal(sweep(pop.currentProfile),true,'actual selected kid profile clears its whole submitted segment');
 assert.equal(audit.verify(pop).ok,true);assert.equal(audit.verify(pop).kind,'clear-form-switch');
 assert.throws(()=>audit.run(1/60,()=>{throw Error('control update failure');}),/control update failure/);
 assert.equal(G.physics._nativeContacts,original.contacts);assert.equal(G.level.triangleWorld.triangle,original.triangle);assert.equal(G.level.triangleWorld._capsuleDistance,original.distance);
 assert.equal(hash(),before,'instrumentation preserves original source geometry, flags and mask');
});
